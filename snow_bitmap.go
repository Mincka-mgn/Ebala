func snowDrawBitmapText(img *image.RGBA, x, y, scale int, s string, c color.RGBA) {
	for _, r := range s {
		g, ok := snowGlyphs[r]
		if !ok {
			g = snowGlyphs[' ']
		}
		for row, line := range g {
			for col, bit := range line {
				if bit == '1' {
					for dx := 0; dx < scale; dx++ {
						for dy := 0; dy < scale; dy++ {
							xx := x + col*scale + dx
							yy := y + row*scale + dy
							if image.Pt(xx, yy).In(img.Bounds()) {
								img.SetRGBA(xx, yy, c)
							}
						}
					}
				}
			}
		}
		x += 6 * scale
	}
}
