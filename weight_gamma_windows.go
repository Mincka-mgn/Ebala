func weightShowGammaReference() {
	owner := hwnd
	if catalogEditorWindow != 0 {
		owner = catalogEditorWindow
	}
	pMsgBox.Call(owner, uintptr(unsafe.Pointer(ptr(gammaReference))), uintptr(unsafe.Pointer(ptr("Коэффициент надёжности по нагрузке γf"))), MB_ICONINFORMATION)
}
